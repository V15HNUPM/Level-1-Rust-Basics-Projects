pub fn c_2_k(c: f32) -> f32 {
    c + 273.15
}

pub fn c_2_f(c: f32) -> f32 {
    (c * 9.0 / 5.0) + 32.0
}

pub fn k_2_c(k: f32) -> f32 {
    k - 273.15
}

pub fn k_2_f(k: f32) -> f32 {
    ((k - 273.15) * 9.0 / 5.0) + 32.0
}

pub fn f_2_k(f: f32) -> f32 {
    ((f - 32.0) * 5.0 / 9.0) + 273.15
}

pub fn f_2_c(f: f32) -> f32 {
    (f - 32.0) * 5.0 / 9.0
}